/**
 * Generates dist/_headers with a CSP that hashes every inline script.
 *
 * Astro emits its island-hydration runtime as inline <script> tags, which a
 * plain `script-src 'self'` blocks. That fails only in production, because
 * _headers is a Netlify feature and never applies to `astro preview`.
 *
 * Hashing keeps the policy strict without 'unsafe-inline'. Hashes change with
 * every build, so this runs after `astro build` rather than being hand-written.
 */
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

const DIST = 'dist';

/** Inline <script> blocks only: anything with src= is covered by 'self'. */
const INLINE_SCRIPT = /<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi;

async function htmlFiles(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await htmlFiles(full)));
    else if (entry.name.endsWith('.html')) out.push(full);
  }
  return out;
}

const files = await htmlFiles(DIST);
const hashes = new Set();

for (const file of files) {
  const html = await readFile(file, 'utf8');
  for (const [, body] of html.matchAll(INLINE_SCRIPT)) {
    if (!body.trim()) continue;
    hashes.add(`'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`);
  }
}

const csp = [
  "default-src 'self'",
  `script-src 'self' ${[...hashes].join(' ')}`.trim(),
  "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
  "font-src 'self' https://fonts.gstatic.com",
  "img-src 'self' data: blob:",
  "worker-src 'self' blob:",
  "connect-src 'self'",
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'self' mailto:",
  "object-src 'none'",
].join('; ');

const headers = `# Generated by scripts/build-csp.mjs. Do not edit by hand.
/*
  X-Frame-Options: DENY
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: geolocation=(), camera=(), microphone=(), interest-cohort=()
  Cross-Origin-Opener-Policy: same-origin
  Content-Security-Policy: ${csp}

# Fingerprinted build assets are immutable
/_astro/*
  Cache-Control: public, max-age=31536000, immutable
`;

await writeFile(join(DIST, '_headers'), headers, 'utf8');

console.log(
  `[csp] ${hashes.size} inline script hash(es) across ${files.length} page(s) -> ${relative(process.cwd(), join(DIST, '_headers'))}`
);
